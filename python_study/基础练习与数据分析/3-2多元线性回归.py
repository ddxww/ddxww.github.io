import pa1 as pd
import statsmodels.api as sm

# 1. 构建数据集（20条完整数据）
data = {
    'x1': [5.5, 2.5, 8.0, 3.0, 3.0, 2.9, 8.0, 9.0, 4.0, 6.5, 5.5, 5.0, 6.0, 5.0, 3.5, 8.0, 6.0, 4.0, 7.5, 7.0],
    'x2': [31, 55, 67, 50, 38, 71, 30, 56, 42, 73, 60, 44, 50, 39, 55, 70, 40, 50, 62, 59],
    'x3': [10, 8, 12, 7, 8, 12, 12, 5, 8, 5, 11, 12, 6, 10, 10, 6, 11, 11, 9, 9],
    'x4': [8, 6, 9, 16, 15, 17, 8, 10, 4, 16, 7, 12, 6, 4, 4, 14, 6, 8, 13, 11],
    'Y': [79.3, 200.1, 163.2, 200.1, 146.0, 177.7, 30.9, 291.9, 160.0, 339.4, 159.6, 86.3, 237.5, 107.2, 155.0, 201.4, 100.2, 135.8, 223.3, 195.0]
}
df = pd.DataFrame(data)
print(df)
# 2. 定义自变量和因变量，添加截距项
X = df[['x1', 'x2', 'x3', 'x4']]
Y = df['Y']
X = sm.add_constant(X)  # 必须添加，否则模型不含截距 β0

# 3. 拟合多元线性回归模型
model = sm.OLS(Y, X)
results = model.fit()
# 4. 输出完整结果（含系数表）
print("=== 模型完整结果 ===")
print(results.summary())

# 5. 单独提取各 β 系数
print("\n=== 各 β 系数明细 ===")
print("β0（截距项）:", results.params['const'])
print("β1（x1: 推销开支）:", results.params['x1'])
print("β2（x2: 实际账目数）:", results.params['x2'])
print("β3（x3: 同类商品竞争数）:", results.params['x3'])
print("β4（x4: 地区销售潜力）:", results.params['x4'])